#!/usr/bin/env python3
"""Draws icons/icon.svg: a bound archtop f-hole in brass over black.
Anatomy: a long thin S-shaped stem; each end hooks over into a round eye that hangs beside
the stem; a pointed wing on the outside of each hook; two small nicks at the waist.
Run it, then tools/render_icons.sh for the PNGs.  (python3 tools/fhole.py [out.svg])"""
import math, os, sys
S = 512
BG, FG = '#0b0b0d', '#f2ad3d'
SCALE = 1.08

def bez(p, t):
    (x0, y0), (x1, y1), (x2, y2), (x3, y3) = p
    u = 1 - t
    return (u*u*u*x0 + 3*u*u*t*x1 + 3*u*t*t*x2 + t*t*t*x3, u*u*u*y0 + 3*u*u*t*y1 + 3*u*t*t*y2 + t*t*t*y3)
def bump(t, c, s): return math.exp(-((t - c) / s) ** 2)

# main stem, top to bottom
STEM = [(290, 128), (238, 222), (284, 302), (224, 388)]
R_HOOK, HOOK_DEG, EYE_R = 35, 196, 22

def stem_half(t):
    return 8.5 + 6 * bump(t, 0.07, 0.17) + 6 * bump(t, 0.93, 0.17)

def hook(p0, heading, w0):
    """Arc turning right (screen) from p0, getting thinner; returns [(x, y, half)] and the end."""
    out = []; x, y = p0; th = heading
    steps = 60; ds = R_HOOK * math.radians(HOOK_DEG) / steps
    for i in range(1, steps + 1):
        th += ds / R_HOOK
        x += math.cos(th) * ds; y += math.sin(th) * ds
        f = i / steps
        out.append((x, y, w0 + (6.5 - w0) * f ** 0.6))
    return out, (x, y)

N = 300
main = [(*bez(STEM, i / N), stem_half(i / N)) for i in range(N + 1)]
ang = lambda a, b: math.atan2(b[1] - a[1], b[0] - a[0])
top_head = ang(bez(STEM, 0.01), bez(STEM, 0.0))           # heading up out of the stem's top
bot_head = ang(bez(STEM, 0.99), bez(STEM, 1.0))           # heading down out of the bottom
top_arc, top_end = hook(bez(STEM, 0), top_head, stem_half(0))
bot_arc, bot_end = hook(bez(STEM, 1), bot_head, stem_half(1))
line = top_arc[::-1] + main + bot_arc                       # one centreline: top eye → bottom eye

def edges(pl, nick_at):
    L, Rr = [], []
    for i, (x, y, w) in enumerate(pl):
        a, b = pl[max(0, i - 1)], pl[min(len(pl) - 1, i + 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]; d = math.hypot(dx, dy) or 1
        nx, ny = -dy / d, dx / d
        k = abs(i - nick_at)
        cut = 5.5 * (1 - k / 8) if k < 8 else 0           # the two nicks at the waist
        L.append((x + nx * (w - cut), y + ny * (w - cut))); Rr.append((x - nx * (w - cut), y - ny * (w - cut)))
    return L + Rr[::-1]

body = edges(line, len(top_arc) + N // 2)

def wing(base_t, head, side, span=0.26, flare=9, reach=21):
    """A blade on the outside of a hook: the stem's outer edge flares out and ends in a point
    that carries on past the hook."""
    pts = []
    for j in range(25):
        f = j / 24                                   # 0 = far down the stem, 1 = at the hook
        t = base_t + (span * (1 - f) if base_t < 0.5 else -span * (1 - f))
        i = int(round(t * N)); x, y, w = main[i]
        a, b = main[max(0, i - 1)], main[min(N, i + 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]; d = math.hypot(dx, dy); nx, ny = -dy / d * side, dx / d * side
        o = w + flare * f ** 1.6
        pts.append((x + nx * o, y + ny * o))
    x, y, w = main[int(base_t * N)]
    hx, hy = math.cos(head), math.sin(head)
    a, b = main[max(0, int(base_t * N) - 1)], main[min(N, int(base_t * N) + 1)]
    dx, dy = b[0] - a[0], b[1] - a[1]; d = math.hypot(dx, dy); nx, ny = -dy / d * side, dx / d * side
    pts.append((x + hx * reach + nx * (w + flare + 5), y + hy * reach + ny * (w + flare + 5)))   # the point
    pts.append((x + hx * 4, y + hy * 4))
    i0 = int((base_t + (span if base_t < 0.5 else -span)) * N); pts.append(main[i0][:2])
    return pts

w_top = wing(0.0, top_head, 1)
w_bot = wing(1.0, bot_head, -1)

def path(poly): return 'M' + ' L'.join(f'{x:.1f} {y:.1f}' for x, y in poly) + ' Z'
shape = (f'<path d="{path(body)}"/><path d="{path(w_top)}"/><path d="{path(w_bot)}"/>'
         + ''.join(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{EYE_R}"/>' for x, y in (top_end, bot_end)))

BIND = '--bind' in sys.argv
layers = (f'''  <g fill="{FG}" stroke="{FG}" stroke-width="19" stroke-linejoin="round">{shape}</g>
  <g fill="{BG}" stroke="{BG}" stroke-width="11" stroke-linejoin="round">{shape}</g>
''' if BIND else '') + f'  <g fill="{FG}">{shape}</g>\n'
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {S} {S}">
  <rect width="{S}" height="{S}" rx="112" fill="{BG}"/>
  <!-- archtop f-hole; generated by tools/fhole.py -->
  <g transform="translate(256 258) scale({SCALE}) translate(-256 -258)">
{layers}  </g>
</svg>
'''
args = [a for a in sys.argv[1:] if not a.startswith('--')]
out = args[0] if args else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'icons', 'icon.svg')
open(out, 'w').write(svg)
print('wrote', out)
